#!/usr/bin/env python3
"""Pin package repositories at each fixture's pre-fix commit.

BeeAI's e2e suite clones pre-fix repositories from ``mock_data/<agent>/`` so an
applicability check sees the vulnerable tree. The gateway has no per-issue hook
in our harness (the MCP request carries no ``jira_issue``), but it already sets
``GIT_CONFIG_GLOBAL=/git-repos/.mock_gitconfig``, so the same effect can be had
with ``insteadOf`` rules pointing at local bare repos.

``setup`` clones every repo the selected issues need into the git-repos volume
and writes the rewrite config once. ``activate`` pins the branch refs for one
issue before it runs — necessary because two fixtures can share a branch
(expat c10s) at different commits.

Run this through the eval runner (``run_eval.py --pre-fix``), not directly.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
DEFAULT_FIXTURES = Path("/tmp/testing-jiras/mock_data/triage")
GITCONFIG_NAME = ".mock_gitconfig"
MOCK_DIR = "eval-mock"
BASE_DIR = "base"
ACTIVE_DIR = "active"


def _slug(url: str) -> str:
    return re.sub(r"[^A-Za-z0-9]+", "-", url.split("://", 1)[-1]).strip("-").lower()


def _gitconfig_for(issue: str, repos: list[dict]) -> str:
    """Rewrite rules for one issue, pointing at its own clone.

    Per-issue clones matter: a global pin leaks state between issues. RHEL-114607
    asks for rhel-10.2, which its fixture does not pin, and inherited the ref that
    RHEL-177992 had left behind — so applicability inspected the wrong source.
    """
    lines = ["# Generated by files/opencode/eval/prepare_mock_repos.py — do not edit."]
    for repo in repos:
        slug = _slug(repo["remote_url"])
        lines.append(f'[url "file:///git-repos/{MOCK_DIR}/{ACTIVE_DIR}/{issue}/{slug}.git"]')
        lines.append(f"\tinsteadOf = {repo['remote_url']}")
        lines.append(f"\tinsteadOf = {repo['remote_url']}.git")
    return "\n".join(lines) + "\n"


def _token() -> str | None:
    if token := os.getenv("GITLAB_TOKEN"):
        return token
    env_file = REPO / ".secrets/mcp-gateway.env"
    if env_file.is_file():
        for line in env_file.read_text().splitlines():
            if line.startswith("GITLAB_TOKEN="):
                return line.split("=", 1)[1].strip()
    return None


def _auth_url(url: str, token: str | None) -> str:
    if token and url.startswith("https://gitlab.com/redhat/"):
        return url.replace("https://", f"https://oauth2:{token}@", 1)
    return url


def _git(*args: str, cwd: Path | None = None, check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["git", *args], cwd=cwd, capture_output=True, text=True, check=check, timeout=900
    )


def _make_readable(root: Path) -> None:
    """The gateway runs as a different uid; keep the fixtures world-readable."""
    os.chmod(root, 0o755)
    for dirpath, dirnames, filenames in os.walk(root):
        for name in dirnames:
            os.chmod(os.path.join(dirpath, name), 0o755)
        for name in filenames:
            os.chmod(os.path.join(dirpath, name), 0o644)


def volume_path(container: str = "", tool: str = "podman") -> Path:
    """Locate the host directory behind the gateway's /git-repos mount."""
    return _mount_path(container or _gateway(tool), "/git-repos", tool)


def work_path(container: str = "", tool: str = "podman") -> Path:
    """Locate the host directory behind the agent's /home/beeai/work mount."""
    return _mount_path(container or _agent(tool), "/home/beeai/work", tool)


def _mount_path(container: str, destination: str, tool: str) -> Path:
    out = subprocess.run(
        [tool, "inspect", container, "--format",
         '{{range .Mounts}}{{.Source}}|{{.Destination}}{{"\\n"}}{{end}}'],
        capture_output=True, text=True, check=True,
    ).stdout
    for line in out.splitlines():
        source, _, dest = line.partition("|")
        if dest.strip() == destination:
            return Path(source.strip())
    raise SystemExit(f"could not find the {destination} mount on {container}")


def _agent(tool: str) -> str:
    return _container_matching("opencode-agent", tool)


def _gateway(tool: str) -> str:
    return _container_matching("mcp-gateway", tool)


def _container_matching(needle: str, tool: str) -> str:
    names = subprocess.run(
        [tool, "ps", "--format", "{{.Names}}"], capture_output=True, text=True, check=True
    ).stdout.split()
    for name in names:
        if needle in name:
            return name
    raise SystemExit(f"{needle} container is not running")


def load_fixtures(issues: list[str], fixtures_dir: Path = DEFAULT_FIXTURES) -> dict[str, list[dict]]:
    wanted: dict[str, list[dict]] = {}
    for issue in issues:
        path = fixtures_dir / f"{issue}.json"
        if not path.is_file():
            print(f"  no repo fixture for {issue}; skipping", file=sys.stderr)
            continue
        wanted[issue] = json.loads(path.read_text()).get("repos", [])
    return wanted


def setup(
    issues: list[str],
    *,
    fixtures_dir: Path = DEFAULT_FIXTURES,
    container: str = "",
    tool: str = "podman",
) -> dict[str, list[dict]]:
    """Clone the needed base mirrors. Returns a manifest."""
    volume = volume_path(container, tool)
    store = volume / MOCK_DIR
    base = store / BASE_DIR
    base.mkdir(parents=True, exist_ok=True)
    store.mkdir(parents=True, exist_ok=True)
    os.chmod(store, 0o755)  # the gateway runs as a different uid
    os.chmod(base, 0o755)
    token = _token()
    manifest = load_fixtures(issues, fixtures_dir)

    # Migrate the flat layout used before per-issue clones existed.
    for legacy in store.glob("*.git"):
        if legacy.is_dir():
            legacy.rename(base / legacy.name)

    repos: dict[str, str] = {}
    for issue_repos in manifest.values():
        for repo in issue_repos:
            repos[repo["remote_url"]] = _slug(repo["remote_url"])

    for url, slug in sorted(repos.items()):
        dest = base / f"{slug}.git"
        if dest.is_dir():
            _make_readable(dest)
            continue
        print(f"  cloning {url}", flush=True)
        _git("clone", "--bare", "--quiet", _auth_url(url, token), str(dest))
        # Keep the credential out of the on-disk config.
        _git("remote", "set-url", "origin", url, cwd=dest, check=False)
        _make_readable(dest)

    for issue, issue_repos in manifest.items():
        for repo in issue_repos:
            dest = base / f"{repos[repo['remote_url']]}.git"
            sha = repo["pre_fix_ref"]
            if _git("cat-file", "-e", f"{sha}^{{commit}}", cwd=dest, check=False).returncode:
                print(f"  fetching {sha[:10]} for {dest.name}", flush=True)
                _git("fetch", "--quiet", "origin", sha, cwd=dest, check=False)

    return manifest


def activate(issue: str, manifest: dict[str, list[dict]], *, tool: str = "podman", container: str = "") -> None:
    """Give this issue its own clone, pinned only to the branches it models."""
    repos = manifest.get(issue, [])
    if not repos:
        return
    volume = volume_path(container, tool)
    store = volume / MOCK_DIR
    active = store / ACTIVE_DIR / issue
    active.mkdir(parents=True, exist_ok=True)
    os.chmod(store / ACTIVE_DIR, 0o755)
    os.chmod(active, 0o755)

    keep: dict[str, set[str]] = {}
    for repo in repos:
        slug = _slug(repo["remote_url"])
        dest = active / f"{slug}.git"
        if not dest.is_dir():
            source = store / BASE_DIR / f"{slug}.git"
            # A local clone hardlinks objects, so it is cheap and self-contained.
            # --shared would write a host-path alternates file the gateway cannot
            # resolve.
            _git("clone", "--bare", "--quiet", str(source), str(dest))
            _make_readable(dest)
        keep.setdefault(slug, set()).add(repo["branch"])

    for repo in repos:
        dest = active / f"{_slug(repo['remote_url'])}.git"
        result = _git(
            "update-ref", f"refs/heads/{repo['branch']}", repo["pre_fix_ref"], cwd=dest, check=False
        )
        if result.returncode:
            print(
                f"  warning: could not pin {dest.name} {repo['branch']} "
                f"to {repo['pre_fix_ref'][:10]}: {result.stderr.strip()[:120]}",
                file=sys.stderr,
            )

    # Drop branches this issue does not model. Leaving them would let a lookup for
    # an unpinned branch fall through to the base mirror's live head.
    for slug, branches in keep.items():
        dest = active / f"{slug}.git"
        refs = _git("for-each-ref", "--format=%(refname:short)", "refs/heads", cwd=dest).stdout.split()
        for ref in refs:
            if ref not in branches:
                _git("update-ref", "-d", f"refs/heads/{ref}", cwd=dest, check=False)

    config_path = volume / GITCONFIG_NAME
    config_path.write_text(_gitconfig_for(issue, repos))
    os.chmod(config_path, 0o644)
    _make_readable(active)


def write_provenance(
    issue: str,
    manifest: dict[str, list[dict]],
    *,
    tool: str = "podman",
    container: str = "",
) -> Path | None:
    """Freeze "what shipped" for the agent, so Brew does not leak today's build.

    The fixtures pin git and Jira to a past date; Brew still answers with today's
    candidate, which already contains the fix. The skill reads this manifest (see
    OVERRIDE_PATH in provenance.py) and reports the pinned commit instead.
    """
    repos = manifest.get(issue)
    if not repos:
        return None
    entries: dict[str, dict[str, dict]] = {}
    for repo in repos:
        entries.setdefault(repo["package"], {})[repo["branch"]] = {
            "commit": repo["pre_fix_ref"],
            "repository": repo["remote_url"],
        }
    payload = json.dumps({"eval_fixture": True, "issue": issue, "entries": entries}, indent=2)
    # The work volume is owned by the container user (compose mounts it with :U),
    # so write through the container rather than from the host.
    container = container or _agent(tool)
    result = subprocess.run(
        [
            tool,
            "exec",
            "-i",
            container,
            "sh",
            "-c",
            "mkdir -p /home/beeai/work/.eval && "
            "cat > /home/beeai/work/.eval/provenance.json && "
            "chmod 644 /home/beeai/work/.eval/provenance.json",
        ],
        input=payload,
        text=True,
        capture_output=True,
    )
    if result.returncode:
        print(f"  warning: could not write provenance override: {result.stderr.strip()[:160]}", file=sys.stderr)
        return None
    return Path(f"/home/beeai/work/.eval/provenance.json")


def main(argv: list[str]) -> int:
    if len(argv) < 2:
        print("usage: prepare_mock_repos.py <issue> [<issue> ...]", file=sys.stderr)
        return 2
    manifest = setup(argv[1:])
    for issue, repos in manifest.items():
        activate(issue, manifest)
        pinned = ", ".join(f"{r['branch']}@{r['pre_fix_ref'][:10]}" for r in repos)
        print(f"{issue}: {pinned}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
